    def 解释调用结构(自己, 语法单元):
        结构名称 = 语法单元.get("名称")
        参数列表 = 语法单元.get("参数")
        参数列表 = 自己.解释参数列表(参数列表)
        函数对象 = getattr(内置函数, 结构名称, None)
        if callable(函数对象): 返回结果 = 函数对象(*参数列表)
        return 返回结果

    def 解释常量定义(自己, 语法单元):
        名称 = 语法单元.get("名称")
        量值 = 语法单元.get("量值")
        量值 = 自己.解析参数单元(量值)
        自己.变量列表[名称] = 量值

    def 解释参数列表(自己, 单元列表):
        参数列表 = []
        for 参数单元 in 单元列表:
            参数量值 = 自己.解析参数单元(参数单元)
            参数列表.append(参数量值)
        return 参数列表

    
    def 解析参数单元(自己, 参数单元):
        参数类型 = 参数单元.get("类型")
        match 参数类型:
            case "结构":
                return 自己.解释调用结构(参数单元)
            case "文本":
                return 参数单元.get("数值")
            case "数字":
                return int(参数单元.get("数值")) -1
            case "名称":
                return 自己.变量列表.get(参数单元.get("名称"))
            case _:
                print("未知参数类型", 参数类型)

    def 求值(自己, 项):
        if isinstance(项, dict):
            类型 = 项.get("类型")
            数值 = 项.get("数值")
            if 类型 == "文本":
                return str(数值)
            if 类型 == "数字":
                return int(数值) -1
            return 数值

        # 字符串形态：可能是变量名，也可能是字面量
        if isinstance(项, str):
            if 项 in 自己.变量表:
                return 自己.变量表[项]
            # 尝试当数字
            try:
                return int(项)
            except ValueError:
                return 项

        return 项


