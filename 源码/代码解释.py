
from 内置函数 import 索引内置函数, 运行内置函数


def 比较(运算, 左, 右):
    """执行一次比较运算。"""
    try:
        match 运算:
            case "==": return 左 == 右
            case "!=": return 左 != 右
            case "<": return 左 < 右
            case "<=": return 左 <= 右
            case ">": return 左 > 右
            case ">=": return 左 >= 右
    except TypeError:
        print(f"「{左}」与「{右}」无法用「{运算}」比较")
        return False
    print("未知比较运算符", 运算)
    return False

class 代码解释:
    def __init__(自己, 变量列表 = {}):
        自己.结构列表 = {}
        自己.函数列表 = {}
        自己.函数返回 = None
        自己.变量列表 = 变量列表

    def 解释列表(自己, 语法列表):
        for 语法单元 in 语法列表:
            自己.解释单元(语法单元)
            # 执行到返回语句就立刻停下，不再执行后面的语句
            if 自己.函数返回 is not None:
                return 自己.函数返回
        if 自己.函数返回 is not None:
            return 自己.函数返回

    def 解释单元(自己, 语法单元):
        语句类型 = 语法单元.get("语句")
        match 语句类型:
            case "类型定义":
                自己.解释类型定义(语法单元)
            case "常量定义":
                自己.解释常量定义(语法单元)
            case "变量定义":
                自己.解释变量定义(语法单元)
            case "容量定义":
                自己.解释容量定义(语法单元)
            case "调用结构":
                自己.解释调用语句(语法单元)
            case "自增语句":
                自己.解释自增语句(语法单元)
            case "赋值语句":
                自己.解释赋值语句(语法单元)
            case "模型结构":
                自己.解释模型结构(语法单元)
            case "函数结构":
                自己.解释函数结构(语法单元)
            case "循环语句":
                自己.解释循环语句(语法单元)
            case "条件语句":
                自己.解释条件语句(语法单元)
            case "分支语句":
                自己.解释分支语句(语法单元)
            case "返回语句":
                自己.解释返回语句(语法单元)
            case "管道访问":
                自己.解释管道访问(语法单元)
            case "数据访问":
                自己.解释管道访问(语法单元)
            case "安全访问":
                自己.解释管道访问(语法单元)

            case _:
                print("未知语句类型", 语句类型)

    def 解释调用结构(自己, 语法单元):
        # 管道调用：把左边的值作为第一个参数，右边调用照常求值
        管道值 = 语法单元.get("管道")
        if 管道值 is not None:
            调用单元 = 语法单元.get("结构") or {}
            参数列表 = [自己.解析参数单元(管道值)]
            参数列表 += 自己.解释参数列表(调用单元.get("参数") or [])
            return 自己.执行调用(调用单元.get("名称"), 参数列表)

        return 自己.执行调用(语法单元.get("名称"),
                             自己.解释参数列表(语法单元.get("参数")))

    def 解释调用语句(自己, 语法单元):
        """调用出现在语句位置：如果它有返回值，提示结果被丢弃。"""
        结果 = 自己.解释调用结构(语法单元)
        名称 = 语法单元.get("名称") or (语法单元.get("结构") or {}).get("名称")
        if 结果 is not None and 自己.有返回值(名称):
            print(f"提示：「{名称}」的返回值没有被使用，"
                  f"如需保存请写成「变量 文本:结果 = {名称}(...)」")

    def 有返回值(自己, 结构名称):
        """判断一个函数是否写了返回语句。"""
        结构对象 = 自己.索引定义结构(结构名称)
        if not 结构对象:
            return False
        return any(语句.get("语句") == "返回语句"
                   for 语句 in 结构对象.get("代码") or []
                   if isinstance(语句, dict))

    def 执行调用(自己, 结构名称, 参数列表):
        """参数已是求值后的值，直接按名称找到函数或内置函数执行。"""
        if 自己.索引定义结构(结构名称):
            return 自己.运行定义结构(结构名称, 参数列表)
        if 索引内置函数(结构名称):
            return 运行内置函数(结构名称, 参数列表)
        print(f"未定义的函数「{结构名称}」")

    def 解释循环语句(自己, 语法单元):
        while 自己.求条件(语法单元.get("条件")):
            自己.解释列表(语法单元.get("代码") or [])
            if 自己.函数返回 is not None:
                return 自己.函数返回

    def 解释条件语句(自己, 语法单元):
        if 自己.求条件(语法单元.get("条件")):
            语句列表 = 语法单元.get("代码") or []
        else:
            语句列表 = 语法单元.get("或者代码") or []
        return 自己.解释列表(语句列表)

    def 解释返回语句(自己, 语法单元):
        自己.函数返回 = 自己.解析参数单元(语法单元.get("量值"))
        return 自己.函数返回

    def 解释赋值语句(自己, 语法单元):
        名称 = 语法单元.get("名称")
        自己.变量列表[名称] = 自己.解析参数单元(语法单元.get("量值"))

    def 解释自增语句(自己, 语法单元):
        名称 = 语法单元.get("名称")
        运算 = 语法单元.get("运算")
        当前值 = 自己.查找变量(名称)
        if not isinstance(当前值, int):
            print(f"「{名称}」不是数字，无法自增")
            return
        自己.变量列表[名称] = 当前值 + (1 if 运算 == "++" else -1)

    def 求条件(自己, 项):
        """求一个条件的真假：比较表达式或单个值。"""
        if not isinstance(项, dict):
            return bool(项)
        if 项.get("类型") == "比较":
            左 = 自己.解析参数单元(项.get("左"))
            右 = 自己.解析参数单元(项.get("右"))
            return 比较(项.get("运算"), 左, 右)
        return bool(自己.解析参数单元(项))
    
    def 索引定义结构(自己, 结构名称:str):
        return 自己.结构列表.get(结构名称)

    def 运行定义结构(自己, 结构名称:str, 参数列表:list):
        结构对象 = 自己.索引定义结构(结构名称)
        语句列表 = 结构对象["代码"]
        # 以内层变量为底，带上外层的变量，再按形参名绑定实参
        变量列表 = dict(自己.变量列表)
        for 形参, 实参 in zip(结构对象.get("参数") or [], 参数列表):
            变量列表[形参.get("量值")] = 实参
        子解释器 = 代码解释(变量列表)
        子解释器.结构列表 = 自己.结构列表
        子解释器.函数列表 = 自己.函数列表
        return 子解释器.解释列表(语句列表)

    def 解释模型结构(自己, 单元):
        pass

    def 解释类型定义(自己, 单元):
        # 类型定义只是给名字起别名，暂时不需要做任何事
        pass

    def 解释函数结构(自己, 单元):
        名称 = 单元.get("名称")
        自己.函数列表[名称] = 单元
        自己.结构列表[名称] = 单元

    def 解释常量定义(自己, 语法单元):
        名称 = 语法单元.get("名称")
        量值 = 语法单元.get("量值")
        量值 = 自己.解析参数单元(量值)
        自己.变量列表[名称] = 量值

    def 解释变量定义(自己, 语法单元):
        自己.解释常量定义(语法单元)

    def 解释容量定义(自己, 语法单元):
        自己.解释常量定义(语法单元)

    def 解释参数列表(自己, 单元列表):
        参数列表 = []
        for 参数单元 in 单元列表:
            参数量值 = 自己.解析参数单元(参数单元)
            参数列表.append(参数量值)
        return 参数列表

    
    def 解析参数单元(自己, 参数单元):
        # 直接给出名称或裸值时（例如 返回 当前文本），按名称查变量
        if not isinstance(参数单元, dict):
            if isinstance(参数单元, str):
                return 自己.查找变量(str(参数单元))
            return 参数单元

        参数类型 = 参数单元.get("类型")
        match 参数类型:
            case "结构":
                return 自己.解释调用结构(参数单元)
            case "文本":
                return 参数单元.get("数值")
            case "数字":
                return int(参数单元.get("数值"))
            case "名称":
                return 自己.查找变量(参数单元.get("名称"))
            case "比较":
                return 自己.求条件(参数单元)
            case _:
                print("未知参数类型", 参数类型)

    def 查找变量(自己, 名称):
        if 名称 in 自己.变量列表:
            return 自己.变量列表[名称]
        print(f"变量「{名称}」未定义")
        return None

    def 求值(自己, 项):
        if isinstance(项, dict):
            类型 = 项.get("类型")
            数值 = 项.get("数值")
            if 类型 == "文本":
                return str(数值)
            if 类型 == "数字":
                return int(数值) -1
            return 数值

        # 字符串形态：可能是变量名，也可能是字面量
        if isinstance(项, str):
            if 项 in 自己.变量表:
                return 自己.变量表[项]
            # 尝试当数字
            try:
                return int(项)
            except ValueError:
                return 项

        return 项


解释工具 = 代码解释()
def 语言代码解释(语法列表):
    解释工具.解释列表(语法列表)