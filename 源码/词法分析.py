# ── 词元 ──────────────────────────────────────────────────────────

class 词元(str):
    """一个词元。

    与 lark 的 Token 一样继承自 str：词元本身就是它的原文，可以直接参与
    字符串运算，也可以 int(词元) 转成数字。另外附带位置与语法含义信息。
    """

    __slots__ = ('种类', '行号', '列号', '起始位置', '结束位置',
                 '词元类型', '限制')

    def __new__(类, 种类, 文本, 行号, 列号, 起始位置, 结束位置,
                词元类型='', 限制=None):
        对象 = super().__new__(类, 文本)
        对象.种类 = 种类
        对象.行号 = 行号
        对象.列号 = 列号
        对象.起始位置 = 起始位置
        对象.结束位置 = 结束位置
        对象.词元类型 = 词元类型
        对象.限制 = 限制
        return 对象

    @property
    def 文本(自己):
        return str(自己)

    def 改名(自己, 词元类型, 限制=None):
        """返回含义被重新认定的同一个词元。"""
        return 词元(自己.种类, str(自己), 自己.行号, 自己.列号,
                    自己.起始位置, 自己.结束位置, 词元类型, 限制)

    def __repr__(自己):
        return f"词元({自己.词元类型!r}, {str(自己)!r})"


# ── 语法树 ────────────────────────────────────────────────────────

class 语法树:
    """与 lark 的 Tree 结构一致，保证下游代码无需修改。"""

    __slots__ = ('data', 'children')

    def __init__(自己, data, children):
        自己.data = data
        自己.children = children

    def __eq__(自己, 其他):
        return (isinstance(其他, 语法树)
                and 自己.data == 其他.data
                and 自己.children == 其他.children)

    def __hash__(自己):
        return hash((自己.data, tuple(自己.children)))

    def __repr__(自己):
        return f"语法树({自己.data!r}, {自己.children!r})"

    def __len__(自己):
        return len(自己.children)

    def 迭代词元(自己):
        """按出现顺序产出所有词元。"""
        for 子节点 in 自己.children:
            if isinstance(子节点, 词元):
                yield 子节点
            elif isinstance(子节点, 语法树):
                yield from 子节点.迭代词元()

    def scan_values(自己, 条件):
        """等价于 lark 的 scan_values。"""
        for 词元对象 in 自己.迭代词元():
            if 条件(词元对象):
                yield 词元对象

    def pretty(自己, 缩进='  '):
        """等价于 lark 的 pretty()。"""
        行列表 = []
        自己._美化(行列表, 0, 缩进)
        return '\n'.join(行列表)

    def _美化(自己, 行列表, 层数, 缩进):
        if 自己.data:
            行列表.append(缩进 * 层数 + str(自己.data))
            层数 += 1
        for 子节点 in 自己.children:
            if isinstance(子节点, 语法树):
                子节点._美化(行列表, 层数, 缩进)
            else:
                行列表.append(缩进 * 层数 + str(子节点))


