class 词法错误(Exception):
    """词法分析或语法分析过程中发现的错误。"""

    def __init__(自己, 说明, 行号, 列号, 位置):
        super().__init__(f'{说明}（第 {行号} 行第 {列号} 列）')
        自己.说明 = 说明
        自己.行号 = 行号
        自己.列号 = 列号
        自己.位置 = 位置


# ── 字符判断 ──────────────────────────────────────────────────────

def 是空白(字符):
    return bool(字符) and 字符.isspace()


def 是数字(字符):
    return bool(字符) and '0' <= 字符 <= '9'


def 是汉字(字符):
    if not 字符:
        return False
    编码 = ord(字符)
    return (0x4E00 <= 编码 <= 0x9FFF        # 基本汉字
            or 0x3400 <= 编码 <= 0x4DBF     # 扩展 A 区
            or 0x20000 <= 编码 <= 0x2A6DF   # 扩展 B 区
            or 0x2A700 <= 编码 <= 0x2CEAF   # 扩展 C 至 G 区
            or 0xF900 <= 编码 <= 0xFAFF     # 兼容汉字
            or 0x2F800 <= 编码 <= 0x2FA1F)  # 兼容汉字补充


def 是名称字符(字符):
    return (bool(字符) and (字符 == '_' or 是汉字(字符)
                            or 'a' <= 字符 <= 'z' or 'A' <= 字符 <= 'Z'
                            or 是数字(字符)))


符号集合 = frozenset('(){}[],:=|.?<>+-*/%!&^~')

# 由两个字符组成的运算符。扫描时必须先于单字符判断，
# 否则「<=」会被拆成「<」和「=」。
两字符运算符 = ('<=', '>=', '==', '!=', '++', '--', '+=', '-=', '&&', '||')

# 三字符运算符：参数收集用的 ...
三字符运算符 = ('...',)

# 比较运算符，用于循环和如果的条件
比较符集合 = frozenset({'==', '!=', '<', '<=', '>', '>='})


# ── 词法扫描 ──────────────────────────────────────────────────────

def 记录行列(代码文本):
    """预先算好每个字符所在的行号与列号（均从 1 开始）。"""
    行号表 = [0] * (len(代码文本) + 1)
    列号表 = [0] * (len(代码文本) + 1)
    行号, 列号 = 1, 1
    for 序号, 字符 in enumerate(代码文本):
        行号表[序号] = 行号
        列号表[序号] = 列号
        行号, 列号 = (行号 + 1, 1) if 字符 == '\n' else (行号, 列号 + 1)
    行号表[len(代码文本)] = 行号
    列号表[len(代码文本)] = 列号
    return 行号表, 列号表


def 扫描词元(代码文本):
    """把代码文本切分为词元列表（忽略空白）。"""
    行号表, 列号表 = 记录行列(代码文本)
    词元列表 = []
    长度 = len(代码文本)
    位置 = 0

    def 生成(种类, 类型, 起, 止):
        return 词元(种类, 代码文本[起:止], 行号表[起], 列号表[起],
                    起, 止, 类型)

    while 位置 < 长度:
        字符 = 代码文本[位置]

        if 是空白(字符):
            位置 += 1
            continue

        起始位置 = 位置

        if 是数字(字符):
            while 位置 < 长度 and 是数字(代码文本[位置]):
                位置 += 1
            if 位置 + 1 < 长度 and 代码文本[位置] == '.' \
                    and 是数字(代码文本[位置 + 1]):
                位置 += 1
                while 位置 < 长度 and 是数字(代码文本[位置]):
                    位置 += 1
            词元列表.append(生成(数字符号, 数字类型, 起始位置, 位置))

        elif 是名称字符(字符):
            while 位置 < 长度 and 是名称字符(代码文本[位置]):
                位置 += 1
            词元列表.append(生成(名称类, '', 起始位置, 位置))

        elif 字符 in ('"', "'"):
            引号 = 字符
            位置 += 1
            while 位置 < 长度 and 代码文本[位置] != 引号:
                位置 += 1
            if 位置 >= 长度:
                raise 词法错误('文本缺少结尾的引号', 行号表[起始位置],
                               列号表[起始位置], 起始位置)
            位置 += 1
            词元列表.append(生成(文本符号, 文本类型, 起始位置, 位置))

        elif 代码文本.startswith(三字符运算符, 位置):
            位置 += 3
            词元列表.append(生成(符号类, 代码文本[起始位置:位置],
                                 起始位置, 位置))

        elif 代码文本.startswith(两字符运算符, 位置):
            位置 += 2
            词元列表.append(生成(符号类, 代码文本[起始位置:位置],
                                 起始位置, 位置))

        elif 字符 == '#':
            # 注释：从 # 到行尾全部忽略
            while 位置 < 长度 and 代码文本[位置] != '\n':
                位置 += 1

        elif 代码文本.startswith('//', 位置):
            # 注释：从 // 到行尾全部忽略
            # 单个 / 仍然是除法和路径分隔符，只有连续两个才算注释
            while 位置 < 长度 and 代码文本[位置] != '\n':
                位置 += 1

        elif 字符 in 符号集合:
            位置 += 1
            词元列表.append(生成(符号类, 字符, 起始位置, 位置))

        else:
            raise 词法错误(f'无法识别的字符「{字符}」', 行号表[起始位置],
                           列号表[起始位置], 起始位置)

    return 词元列表


# ══════════════════════════════════════════════════════════════════
# 未归约词分析
#
# 关键字与状态字面量没有在词法扫描阶段固定下来，而是由分析器按所处位置
# 现场判断：
#
#     语句开头    命中「语句关键字」的词开启对应语句，其余当作调用
#     名称位置    类型名、变量名、参数名、键：一律当作名称
#     值的位置    只有「真」「假」才当作状态字面量
#     数据位置    名称既可当作调用名称，也可当作调用结构
#
# 语句内部出现的「模型」「函数」「循环」「如果」「或者」不能当作名称，
# 以免嵌套语句的边界被误读。
# ══════════════════════════════════════════════════════════════════


class 分析器:
    """把词元列表分析成语法树。"""

    def __init__(自己, 词元列表, 结束位置=None):
        自己.词元列表 = 词元列表
        自己.数量 = len(词元列表)
        自己.位置 = 0
        自己.结束位置 = 结束位置 or (词元列表[-1].结束位置 if 词元列表 else 0)

    # ── 基本工具 ────────────────────────────────────────────────

    def 当前(自己, 偏移=0):
        位置 = 自己.位置 + 偏移
        return 自己.词元列表[位置] if 位置 < 自己.数量 else None

    def 是否文本(自己, 文本, 偏移=0):
        词元对象 = 自己.当前(偏移)
        return 词元对象 is not None and 词元对象.文本 == 文本

    def 读符号(自己, 符号):
        """读到指定符号则前进，否则原地不动。"""
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.种类 == 符号类 \
                and 词元对象.文本 == 符号:
            自己.位置 += 1
            return True
        return False

    def 读关键字(自己, 文本):
        """读到一个关键字，返回它的词元；否则返回 None。"""
        词元对象 = 自己.当前()
        if 词元对象 is None or 词元对象.种类 != 名称类 \
                or 词元对象.文本 != 文本:
            return None
        自己.位置 += 1
        return 词元对象

    def 报错(自己, 说明):
        词元对象 = 自己.当前()
        if 词元对象 is None and 自己.数量:
            末尾 = 自己.词元列表[-1]
            raise 词法错误(说明 + '：代码意外结束',
                           末尾.行号, 末尾.列号 + len(末尾), 末尾.结束位置)
        if 词元对象 is None:
            raise 词法错误(说明 + '：代码意外结束', 1, 1, 0)
        raise 词法错误(f'{说明}：遇到「{词元对象.文本}」',
                       词元对象.行号, 词元对象.列号, 词元对象.起始位置)

    # ── 名称 ────────────────────────────────────────────────────

    def 分析名称(自己):
        """读一个名称，返回 name 节点。

        「返回」不当作名称，这样「条件 && 返回 值」里的表达式会在这里停下。
        """
        词元对象 = 自己.当前()
        if 词元对象 is None or 词元对象.种类 != 名称类:
            return None
        if 词元对象.文本 == '返回':
            return None
        自己.位置 += 1
        return 语法树(节点名称, [词元对象.改名(名称类型)])

    def 分析类型名(自己):
        """读一个类型名，返回 type(name(...)) 节点。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 语法树(节点类型, [名称节点])

    # ── 程序与语句 ──────────────────────────────────────────────

    def 分析程序(自己):
        语句组 = 自己.分析语句组()
        if not 语句组.children:
            自己.报错('程序里没有可执行的语句')
        if 自己.位置 < 自己.数量:
            自己.报错('无法解析这条语句')
        return 语法树(节点开始, [语句组])

    def 分析语句组(自己):
        """一条或多条语句；允许为空（例如函数体暂时留空）。"""
        语句列表 = []
        while 自己.位置 < 自己.数量:
            语句 = 自己.分析语句()
            if 语句 is None:
                break
            语句列表.append(语法树(节点语句项, [语句]))
        return 语法树(节点语句组, 语句列表)

    def 分析语句(自己):
        """分析一条语句，返回语句节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 名称类 and 词元对象.文本 in 语句关键字:
            文本 = 词元对象.文本
            自己.位置 += 1
            语句 = 自己.分析关键字语句(语句关键字[文本])
            if 语句 is None:
                自己.报错(f'「{文本}」语句的写法不正确')
            return 语句
        return 自己.分析普通语句()

    def 分析普通语句(自己):
        """非关键字开头的语句：自增、赋值、管道调用或普通调用。

        依次尝试，采用第一种读得通的写法：
            名称 ++        自增
            名称 = 数据     给已定义的变量重新赋值
            值 | 调用(...)  管道调用
            名称(...)      普通调用
        """
        起始 = 自己.位置
        for 方法 in (自己.分析短路返回,
                     自己.分析自增, 自己.分析赋值,
                     自己.分析下标调用, 自己.分析管道调用,
                     自己.分析调用结构):
            结果 = 方法()
            if 结果 is not None:
                return 结果
            自己.位置 = 起始
        return None

    def 分析短路返回(自己):
        """条件 && 返回 值：条件为真时立刻返回。

        写成一条语句，替代「如果(条件) { 返回 值 }」。
        也支持 || 取反形式：条件 || 返回 值。

        先在本行范围内找到「&& 返回」或「|| 返回」，确认是这种写法后，
        再分别解析条件与返回值。
        """
        起始 = 自己.位置
        起始行 = 自己.词元列表[起始].行号

        # 在语句范围内找到逻辑运算符与「返回」
        运算位置 = None
        动作位置 = None
        扫描位置 = 起始
        深度 = 0
        while 扫描位置 < 自己.数量:
            词元对象 = 自己.词元列表[扫描位置]
            # 只在本行内查找，避免把后面的语句吞进来
            if 词元对象.行号 != 起始行:
                break
            文本 = 词元对象.文本
            if 文本 in ('(', '[', '{'):
                深度 += 1
            elif 文本 in (')', ']', '}'):
                if 深度 == 0:
                    break
                深度 -= 1
            elif 深度 == 0 and 文本 in ('&&', '||'):
                运算位置 = 扫描位置
            elif 深度 == 0 and 运算位置 is not None \
                    and 词元对象.种类 == 名称类:
                # 逻辑运算符之后的第一个名称：返回、赋值或自增的起点
                动作位置 = 扫描位置
                break
            扫描位置 += 1

        if 运算位置 is None or 动作位置 is None or 动作位置 <= 运算位置:
            自己.位置 = 起始
            return None

        # 只处理「返回」和「名称 = 值」「名称++」两类
        后面词元 = 自己.词元列表[动作位置]
        是返回 = 后面词元.文本 == '返回'
        是动作 = (动作位置 + 1 < 自己.数量
                  and 自己.词元列表[动作位置 + 1].文本 in ('=', '++', '--'))
        if not 是返回 and not 是动作:
            自己.位置 = 起始
            return None

        # 解析条件部分（到逻辑运算符之前）
        # 临时把词元列表截断在运算符处，避免表达式把「返回」当成操作数
        原数量 = 自己.数量
        原列表 = 自己.词元列表
        自己.词元列表 = 原列表[:运算位置]
        自己.数量 = 运算位置
        自己.位置 = 起始
        try:
            条件节点 = 自己.分析表达式()
        finally:
            自己.词元列表 = 原列表
            自己.数量 = 原数量
        if 条件节点 is None:
            自己.位置 = 起始
            return None

        自己.位置 = 运算位置

        # 取出运算符（&& 或 ||）
        运算词元 = 自己.当前()
        if 运算词元 is None or 运算词元.文本 not in ('&&', '||'):
            自己.位置 = 起始
            return None
        自己.位置 += 1

        后面词元 = 自己.当前()
        if 后面词元 is None:
            自己.位置 = 起始
            return None

        if 后面词元.文本 == '返回':
            # 条件 && 返回 值
            自己.位置 += 1
            值节点 = 自己.分析项()
            if 值节点 is None:
                自己.位置 = 起始
                return None
            if isinstance(条件节点, 语法树) and 条件节点.data == 节点逻辑:
                条件节点 = 条件节点.children[1]
            return 语法树(节点短路返回, [运算词元, 条件节点, 值节点])

        # 条件 && 名称 = 值 / 名称++ / 名称--
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            自己.位置 = 起始
            return None

        下一个 = 自己.当前()
        if 下一个 is not None and 下一个.文本 in ('++', '--'):
            自己.位置 += 1
            动作节点 = 语法树(节点自增, [下一个, 名称节点])
        elif 自己.读符号('='):
            值节点 = 自己.分析项()
            if 值节点 is None:
                自己.位置 = 起始
                return None
            动作节点 = 语法树(节点赋值, [名称节点, 值节点])
        else:
            自己.位置 = 起始
            return None

        if isinstance(条件节点, 语法树) and 条件节点.data == 节点逻辑:
            条件节点 = 条件节点.children[1]
        return 语法树(节点短路语句, [运算词元, 条件节点, 动作节点])



    def 分析项(自己):
        """返回语句后面可以跟的值。"""
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.种类 == 符号类 \
                and 词元对象.文本 in ('[', '{'):
            值节点 = 自己.分析值()
            return 值节点
        return 自己.分析表达式()

    def 分析赋值(自己):
        """名称 = 数据；也支持 名称[键] = 数据。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None

        # 成员赋值：解析器.optionxform = str
        if 自己.读符号('.'):
            成员节点 = 自己.分析名称()
            if 成员节点 is None or not 自己.读符号('='):
                return None
            数据节点 = 自己.分析数据()
            if 数据节点 is None:
                return None
            return 语法树(节点成员赋值, [名称节点, 成员节点, 数据节点])

        # 下标赋值：结果[键] = 值，也支持 结果[键1][键2] = 值
        键列表 = []
        while 自己.读符号('['):
            键节点 = 自己.分析加减()
            if 键节点 is None or not 自己.读符号(']'):
                return None
            键列表.append(键节点)

        if not 自己.读符号('='):
            return None
        数据节点 = 自己.分析数据()
        if 数据节点 is None:
            return None
        if 键列表:
            return 语法树(节点下标赋值, [名称节点] + 键列表 + [数据节点])
        return 语法树(节点赋值, [名称节点, 数据节点])

    def 分析自增(自己):
        """名称 ++ 或 名称 --，只能用于变量。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        词元对象 = 自己.当前()
        if 词元对象 is None or 词元对象.种类 != 符号类 \
                or 词元对象.文本 not in ('++', '--'):
            return None
        自己.位置 += 1
        return 语法树(节点自增, [词元对象, 名称节点])

    def 分析管道调用(自己):
        """值 | 调用(...)：把左边的值作为第一个参数传给右边的调用。"""
        值节点 = 自己.分析操作数()
        if 值节点 is None:
            return None
        if not 自己.读符号('|'):
            return None
        调用节点 = 自己.分析调用结构()
        if 调用节点 is None:
            return None
        return 语法树(节点管道, [值节点, 调用节点])

    def 分析关键字语句(自己, 规则名):
        if 规则名 in ('定义类型', '定义常量', '定义变量', '定义容量'):
            return 自己.分析定义(规则名)
        if 规则名 in ('模型结构', '函数结构', '结构定义'):
            return 自己.分析结构(规则名)
        if 规则名 == '循环语句':
            return 自己.分析循环()
        if 规则名 == '条件语句':
            return 自己.分析条件()
        if 规则名 == '返回语句':
            return 自己.分析返回()
        return 自己.分析模块(规则名)

    def 分析返回(自己):
        """返回 表达式，也可以是列表等复合值。"""
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.种类 == 符号类 \
                and 词元对象.文本 in ('[', '{'):
            值节点 = 自己.分析值()
            if 值节点 is not None:
                return 语法树(节点返回, [值节点])
        # 管道调用：返回 内容|切割(1, 2)
        起始 = 自己.位置
        管道节点 = 自己.分析管道调用()
        if 管道节点 is not None:
            return 语法树(节点返回, [管道节点])
        自己.位置 = 起始

        表达式 = 自己.分析表达式()
        if 表达式 is None:
            return None
        return 语法树(节点返回, [表达式])

    # ── 表达式 ──────────────────────────────────────────────────

    def 分析表达式(自己):
        """表达式：算术运算与比较运算，按优先级解析。

        优先级由低到高：
            比较   == != < <= > >=
            加减   + -
            乘除   * / %
        一元负号只能用在数字前，如 -5。
        """
        左值 = 自己.分析加减()
        if 左值 is None:
            return None
        # 逻辑运算：甲 and 乙、甲 or 乙、甲 && 乙、甲 || 乙
        if 自己.是否逻辑运算():
            词元对象 = 自己.当前()
            自己.位置 += 1
            右值 = 自己.分析表达式()
            if 右值 is None:
                自己.报错('逻辑运算缺少右边的值')
            return 语法树(节点逻辑, [词元对象, 左值, 右值])

        # 成员运算：子文本 in 文本
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.种类 == 名称类 \
                and 词元对象.文本 == 'in':
            自己.位置 += 1
            右值 = 自己.分析加减()
            if 右值 is None:
                自己.报错('成员运算缺少右边的值')
            return 语法树(节点成员运算, [词元对象, 左值, 右值])
        if 左值 is None:
            return None
        词元对象 = 自己.当前()
        if 词元对象 is None or 词元对象.种类 != 符号类 \
                or 词元对象.文本 not in 比较符集合:
            return 左值
        自己.位置 += 1
        右值 = 自己.分析加减()
        if 右值 is None:
            自己.报错('比较运算缺少右边的值')
        左值 = 语法树(节点比较, [词元对象, 左值, 右值])

        # 比较之后可能还有逻辑运算，如 甲 <= 0 and 乙
        if 自己.是否逻辑运算():
            词元对象 = 自己.当前()
            自己.位置 += 1
            右值 = 自己.分析表达式()
            if 右值 is None:
                自己.报错('逻辑运算缺少右边的值')
            左值 = 语法树(节点逻辑, [词元对象, 左值, 右值])
        return 左值

    def 是否逻辑运算(自己):
        """当前词元是不是逻辑与/或：and or && ||"""
        当前 = 自己.当前()
        if 当前 is None:
            return False
        if 当前.种类 == 符号类:
            return 当前.文本 in ('&&', '||')
        return 当前.种类 == 名称类 and 当前.文本 in ('and', 'or')

    def 分析加减(自己):
        左值 = 自己.分析乘除()
        while 左值 is not None:
            词元对象 = 自己.当前()
            if 词元对象 is None or 词元对象.种类 != 符号类 \
                    or 词元对象.文本 not in ('+', '-'):
                break
            自己.位置 += 1
            右值 = 自己.分析乘除()
            if 右值 is None:
                自己.报错('运算缺少右边的值')
            左值 = 语法树(节点运算, [词元对象, 左值, 右值])
        return 左值

    def 分析乘除(自己):
        左值 = 自己.分析操作数()
        左值 = 自己.分析下标(左值) if 左值 is not None else None
        while 左值 is not None:
            词元对象 = 自己.当前()
            if 词元对象 is None or 词元对象.种类 != 符号类 \
                    or 词元对象.文本 not in ('*', '/', '%'):
                break
            自己.位置 += 1
            右值 = 自己.分析操作数()
            if 右值 is None:
                自己.报错('运算缺少右边的值')
            左值 = 语法树(节点运算, [词元对象, 左值, 右值])
        return 左值

    def 分析下标(自己, 值节点):
        """给一个值加上下标或切片：a[0]、a[1:3]、a[:2]、a[2:]。

        下标之后还可以继续接方法，如 a[节].keys()。
        """
        if not 自己.读符号('['):
            return 值节点

        起点 = None
        if not 自己.是否文本(':'):
            起点 = 自己.分析加减()
            if 起点 is None:
                return None

        # 切片形式
        if 自己.读符号(':'):
            终点 = None
            if not 自己.是否文本(']'):
                终点 = 自己.分析加减()
                if 终点 is None:
                    return None
            if not 自己.读符号(']'):
                return None
            子节点 = [值节点]
            if 起点 is not None:
                子节点.append(语法树(节点切片起, [起点]))
            if 终点 is not None:
                子节点.append(语法树(节点切片止, [终点]))
            return 语法树(节点切片, 子节点)

        if not 自己.读符号(']'):
            return None
        下标节点 = 语法树(节点下标, [值节点, 起点])

        # 连续下标：a[节][键]
        while 自己.当前() is not None and 自己.当前().种类 == 符号类 \
                and 自己.当前().文本 == '[':
            再下标 = 自己.分析下标(下标节点)
            if 再下标 is None:
                return None
            下标节点 = 再下标
            if isinstance(下标节点, 语法树) and 下标节点.data == 节点调用结构:
                return 下标节点

        # 下标之后接方法：a[节].keys()
        if 自己.当前() is not None and 自己.当前().种类 == 符号类 \
                and 自己.当前().文本 == '.':
            自己.位置 += 1
            成员节点 = 自己.分析名称()
            if 成员节点 is None:
                return None
            return 自己.分析调用尾巴(语法树(节点成员, [下标节点, 成员节点]))
        return 下标节点

    def 分析字面量成员(自己):
        """字面量直接调用方法，如 " ".join(...)、"a,b".split(",")。"""
        字面量 = 自己.当前()
        子节点 = 节点数值 if 字面量.种类 == 数字符号 else 节点文本
        值节点 = 语法树(节点值, [语法树(子节点, [字面量])])
        自己.位置 += 1
        if not 自己.读符号('.'):
            return 值节点
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 自己.分析调用尾巴(语法树(节点成员, [值节点, 名称节点]))

    def 分析操作数(自己):
        """操作数：数字、文本或名称。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        # 逻辑非：not 值、!值
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '!':
            自己.位置 += 1
            子值 = 自己.分析操作数()
            if 子值 is None:
                自己.报错('取反缺少值')
            return 语法树(节点取反, [子值])
        if 词元对象.种类 == 名称类 and 词元对象.文本 == 'not':
            自己.位置 += 1
            子值 = 自己.分析操作数()
            if 子值 is None:
                自己.报错('取反缺少值')
            return 语法树(节点取反, [子值])

        # 列表与对象字面量也可以参与运算，如 结果 + [项]
        if 词元对象.种类 == 符号类 and 词元对象.文本 in ('[', '{'):
            值节点 = 自己.分析值()
            return 值节点

        if 词元对象.种类 in (数字符号, 文本符号):
            # 字面量后面可能直接接方法，如 " ".join(...)
            下个 = 自己.当前(1)
            if 下个 is not None and 下个.种类 == 符号类 and 下个.文本 == '.':
                return 自己.分析字面量成员()
            自己.位置 += 1
            子节点 = 节点数值 if 词元对象.种类 == 数字符号 else 节点文本
            return 语法树(节点值, [语法树(子节点, [词元对象])])
        # 一元负号，如 -5
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '-':
            下个 = 自己.当前(1)
            if 下个 is not None and 下个.种类 == 数字符号:
                自己.位置 += 2
                # 整数与小数都要支持
                文本 = str(下个)
                数值 = float(文本) if '.' in 文本 else int(文本)
                负数 = -数值
                return 语法树(节点值, [语法树(节点数值, [词元(
                    数字符号, str(负数), 下个.行号, 下个.列号,
                    下个.起始位置, 下个.结束位置, 数字类型)])])
        if 词元对象.种类 == 名称类:
            # 「返回」不当作操作数，让「条件 && 返回 值」在 && 处断开
            if 词元对象.文本 == '返回':
                return None
            # 方法调用 值.方法(...) 或普通调用 名称(...)
            if 自己.是否文本('(', 1) or 自己.是否文本('.', 1):
                return 自己.分析调用结构()

            名称节点 = 语法树(节点名称, [词元对象.改名(名称类型)])
            自己.位置 += 1
            return 名称节点
        return None

    def 分析定义(自己, 规则名):
        """类型 / 常量 / 变量 / 容量：类型 : 名称 = 数据"""
        类型节点 = 自己.分析类型名()
        if 类型节点 is None or not 自己.读符号(':'):
            return None
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        数据节点 = 自己.分析定义尾()
        if 数据节点 is None:
            return None
        return 语法树(节点名表[规则名], [类型节点, 名称节点, 数据节点])

    def 分析定义尾(自己):
        """定义中名称之后的部分：= 数据

        「= 数据」可以省略，如 `变量 数字:数值`，此时按类型给默认值。
        """
        if not 自己.读符号('='):
            return 语法树(节点数据, [语法树(节点空值, [])])
        数据节点 = 自己.分析数据()
        if 数据节点 is None:
            return None
        return 数据节点

    def 分析结构(自己, 规则名):
        """模型 / 函数：类型 : 名称(参数){语句}，类型可以省略。

        带类型：函数 文本:切割(文本:原文) { ... }
        省类型：函数 切割(原文) { ... }
        """
        起始 = 自己.位置
        类型节点 = None

        # 结构内的「函数() { ... }」：没有名字，作为结构的入口体
        if 规则名 == '函数结构' and 自己.是否文本('('):
            参数节点 = None
            自己.位置 += 1
            参数节点 = 自己.分析参数定义()
            if 参数节点 is None or not 自己.读符号(')'):
                自己.位置 = 起始
                return None
            语句节点 = 自己.分析语句块()
            if 语句节点 is None:
                自己.位置 = 起始
                return None
            无名节点 = 语法树(节点名称, [])
            return 语法树(节点函数结构,
                          [语法树(节点类型, []), 无名节点,
                           参数节点, 语句节点])

        # 尝试「类型 : 名称」，读到冒号才算成立
        名称节点 = 自己.分析名称()
        if 名称节点 is not None and 自己.读符号(':'):
            类型节点 = 语法树(节点类型, [名称节点])
            名称节点 = 自己.分析名称()
        else:
            自己.位置 = 起始
            名称节点 = 自己.分析名称()
            if 名称节点 is not None and 自己.是否文本('('):
                类型节点 = 语法树(节点类型, [])

        if 名称节点 is None or not 自己.读符号('('):
            自己.位置 = 起始
            return None
        参数节点 = 自己.分析参数定义()
        if 参数节点 is None or not 自己.读符号(')'):
            自己.位置 = 起始
            return None
        语句节点 = 自己.分析语句块()
        if 语句节点 is None:
            自己.位置 = 起始
            return None
        if 类型节点 is None:
            类型节点 = 语法树(节点类型, [])
        return 语法树(节点名表[规则名], [类型节点, 名称节点, 参数节点, 语句节点])

    def 分析参数定义(自己):
        """参数：类型 : 名称，类型可以省略，多个参数用逗号分隔。

        省略类型的写法只是为了兼容旧代码，解释时按名称绑定即可。
        """
        参数列表 = []
        if not 自己.是否文本(')'):
            while True:
                第一个名称 = 自己.分析名称()
                if 第一个名称 is None:
                    return None
                if 自己.读符号(':'):
                    # 形如「类型 : 名称」
                    类型节点 = 语法树(节点类型, [第一个名称])
                    名称节点 = 自己.分析名称()
                else:
                    # 形如「名称」，没有类型
                    类型节点 = 语法树(节点类型, [])
                    名称节点 = 第一个名称
                if 名称节点 is None:
                    return None

                # 参数收集：名称... 表示把后面的实参全部收进一个列表
                # 写了类型时，该类型是每个实参应满足的类型
                if 自己.读符号('...'):
                    子节点 = [名称节点]
                    if 类型节点.children:
                        子节点.append(类型节点)
                    参数列表.append(语法树(节点收集参数, 子节点))
                    # 收集参数必须是最后一个
                    if 自己.读符号(',') and not 自己.是否文本(')'):
                        自己.报错('收集参数（名称...）只能放在参数列表最后')
                    break
                # 参数默认值：类型 : 名称 = 值
                子节点 = [类型节点, 名称节点]
                if 自己.读符号('='):
                    默认值节点 = 自己.分析表达式()
                    if 默认值节点 is None:
                        自己.报错('参数默认值写法不正确')
                    子节点.append(默认值节点)
                参数列表.append(语法树(节点参数节, 子节点))
                if not 自己.读符号(','):
                    break
        return 语法树(节点参数组, 参数列表)

    def 分析语句块(自己):
        """{ 语句组 }，返回 statements 节点。"""
        if not 自己.读符号('{'):
            return None
        语句组 = 自己.分析语句组()
        if not 自己.读符号('}'):
            return None
        return 语句组

    def 分析循环(自己):
        """循环(条件){语句}，条件如「当前索引 <= 结束索引」。"""
        if not 自己.读符号('('):
            return None
        条件节点 = 自己.分析表达式()
        if 条件节点 is None or not 自己.读符号(')'):
            return None
        语句组 = 自己.分析语句块()
        if 语句组 is None:
            return None
        return 语法树(节点循环, [条件节点, 语句组])

    def 分析条件(自己):
        """如果(条件){语句} [或者(条件){语句}] [否则{语句}]

        「或者」与「否则」分支都可以省略。
        「否则」等价于「或者(真)」，条件恒成立。
        """
        if not 自己.读符号('('):
            return None
        条件节点 = 自己.分析表达式()
        if 条件节点 is None or not 自己.读符号(')'):
            return None
        如果语句 = 自己.分析语句块()
        if 如果语句 is None:
            return None

        子节点 = [条件节点, 如果语句]
        if 自己.读关键字('或者') is not None:
            if not 自己.读符号('('):
                return None
            或者条件 = 自己.分析表达式()
            if 或者条件 is None or not 自己.读符号(')'):
                return None
            或者语句 = 自己.分析语句块()
            if 或者语句 is None:
                return None
            子节点 += [或者条件, 或者语句]
            # 「或者」之后还可以再接一个「否则」作为兜底
            起始位置 = 自己.位置
            if 自己.读关键字('否则') is not None:
                否则语句 = 自己.分析语句块()
                if 否则语句 is not None:
                    子节点 += [语法树(节点恒真, []), 否则语句]
                else:
                    自己.位置 = 起始位置
        elif 自己.读关键字('否则') is not None:
            # 否则 不需要括号，条件恒成立
            否则语句 = 自己.分析语句块()
            if 否则语句 is None:
                return None
            子节点 += [语法树(节点恒真, []), 否则语句]
        return 语法树(节点条件, 子节点)

    # ── 导入与导出 ──────────────────────────────────────────────

    def 分析模块(自己, 规则名):
        """导入 / 导出 的分派。"""
        if 规则名 == '导入模块':
            return 自己.分析导入()
        return 自己.分析导出()

    def 分析导入(自己):
        """导入 模块名 [命名 别名] [选择 名字, 名字...]

        模块名可以是简单名称，也可以是带 / 的相对路径。
        """
        模块节点 = 自己.分析模块路径()
        if 模块节点 is None:
            return None

        别名 = None
        选择 = []
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.文本 == '命名':
            自己.位置 += 1
            别名 = 自己.分析名称()
            if 别名 is None:
                return None

        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.文本 == '选择':
            自己.位置 += 1
            选择 = 自己.分析名称列表()
            if not 选择:
                return None

        子节点 = [模块节点, 语法树(节点选择, 选择)]
        if 别名 is not None:
            子节点.append(别名)
        return 语法树(节点导入, 子节点)

    def 分析模块路径(自己):
        """模块路径：名称，或用 / 连接的相对路径，也可以写成文本。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None

        # 用引号写成的相对路径，如 "./工具/数学"
        if 词元对象.种类 == 文本符号:
            自己.位置 += 1
            return 语法树(节点模块路径, [词元对象])

        # 名称路径，如 数学、工具/数学、./工具/数学
        if 词元对象.种类 == 符号类 and 词元对象.文本 in ('.', '/', '..'):
            片段 = [词元对象]
            自己.位置 += 1
        elif 词元对象.种类 == 名称类:
            片段 = [词元对象]
            自己.位置 += 1
        else:
            return None

        while True:
            词元对象 = 自己.当前()
            if 词元对象 is None or 词元对象.种类 != 符号类:
                break
            if 词元对象.文本 not in ('/', '.'):
                break
            片段.append(词元对象)
            自己.位置 += 1
            词元对象 = 自己.当前()
            if 词元对象 is not None and 词元对象.种类 == 名称类:
                片段.append(词元对象)
                自己.位置 += 1
        return 语法树(节点模块路径, 片段)

    def 分析名称列表(自己):
        """逗号分隔的名称列表。"""
        名称列表 = []
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return 名称列表
        名称列表.append(名称节点)
        while 自己.读符号(','):
            名称节点 = 自己.分析名称()
            if 名称节点 is None:
                break
            名称列表.append(名称节点)
        return 名称列表

    def 分析导出(自己):
        """导出函数定义，或 导出 名字, 名字...

        导出 文本:索引(文本:a, 数字:位置) { ... }   声明返回类型并定义导出
        导出 add(数字:a, 数字:b) { ... }             省略返回类型
        导出 add, sub                                选中已有函数导出
        """
        起始 = 自己.位置

        # 导出 结构 名称(...) { ... }：定义并导出结构
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.文本 == '结构':
            自己.位置 += 1
            结构 = 自己.分析结构('结构定义')
            if 结构 is not None:
                return 语法树(节点导出函数, [结构])
            自己.位置 = 起始
            return None

        # 形式二优先：导出 函数定义
        # 判断依据是「名字 (」或「类型 : 名字 (」
        if 词元对象 is not None and 词元对象.种类 == 名称类:
            是定义 = 自己.是否文本('(', 1) or 自己.是否文本(':', 1)
            if 是定义:
                结构 = 自己.分析结构('函数结构')
                if 结构 is not None:
                    return 语法树(节点导出函数, [结构])
                自己.位置 = 起始

        # 形式一：导出 名字, 名字...
        选择 = 自己.分析名称列表()
        if 选择:
            return 语法树(节点导出, [语法树(节点选择, 选择)])

        自己.位置 = 起始
        return None

    # ── 调用 ────────────────────────────────────────────────────

    def 分析调用结构(自己):
        """调用结构：名称(参数列表)，也支持 模块.函数(...) 与 值.方法(...)。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 自己.分析调用尾巴(名称节点)

    def 分析下标调用(自己):
        """以名称加下标开头的方法调用，如 结果[节].pop(键)。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        if not 自己.读符号('['):
            return None
        下标 = 自己.分析加减()
        if 下标 is None or not 自己.读符号(']'):
            return None
        值节点 = 语法树(节点下标, [名称节点, 下标])
        if not 自己.读符号('.'):
            return None
        成员节点 = 自己.分析名称()
        if 成员节点 is None:
            return None
        return 自己.分析调用尾巴(语法树(节点成员, [值节点, 成员节点]))

    def 分析调用尾巴(自己, 名称节点):
        """处理 .成员(...) 与 (...)，允许链式调用。"""
        # 「模块.函数」或「值.方法」
        while 自己.读符号('.'):
            成员节点 = 自己.分析名称()
            if 成员节点 is None:
                return None
            名称节点 = 语法树(节点成员, [名称节点, 成员节点])

        if not 自己.读符号('('):
            return None
        参数节点 = 自己.分析参数列表()
        if 参数节点 is None or not 自己.读符号(')'):
            return None
        调用节点 = 语法树(节点调用结构, [名称节点, 参数节点])

        # 调用结果取下标或切片：a.split("/")[0]
        if 自己.当前() is not None and 自己.当前().种类 == 符号类 \
                and 自己.当前().文本 == '[':
            调用节点 = 自己.分析下标(调用节点)
            if 调用节点 is None:
                return None

        # 链式调用：a.strip().split()
        if 自己.当前() is not None and 自己.当前().种类 == 符号类 \
                and 自己.当前().文本 == '.':
            自己.位置 += 1
            成员节点 = 自己.分析名称()
            if 成员节点 is None:
                return None
            返回节点 = 自己.分析调用尾巴(语法树(节点成员, [调用节点, 成员节点]))
            return 返回节点
        return 调用节点

    def 分析参数列表(自己):
        """参数列表：参数项(, 参数项)*，允许为空。

        也支持关键字参数，如 open(路径, encoding="utf-8")。
        返回 arguments 节点。
        """
        参数列表 = []
        if not 自己.是否文本(')'):
            while True:
                # 关键字参数：名称 = 值
                起始 = 自己.位置
                名称节点 = 自己.分析名称()
                if 名称节点 is not None and 自己.读符号('='):
                    值节点 = 自己.分析参数项()
                    if 值节点 is None:
                        return None
                    参数列表.append(语法树(节点关键字参数,
                                           [名称节点, 值节点]))
                else:
                    自己.位置 = 起始
                    参数节点 = 自己.分析参数项()
                    if 参数节点 is None:
                        return None
                    参数列表.append(语法树(节点参数项, [参数节点]))
                if not 自己.读符号(','):
                    break
        return 语法树(节点参数列表, 参数列表)

    # ── 数据与值 ────────────────────────────────────────────────

    def 分析单项表达式(自己):
        """只解析不跨逗号、右括号的表达式，用于函数参数。"""
        左值 = 自己.分析乘除()
        if 左值 is None:
            return None
        左值 = 自己.分析下标(左值)
        if 左值 is None:
            return None
        while True:
            词元对象 = 自己.当前()
            if 词元对象 is None or 词元对象.种类 != 符号类 \
                    or 词元对象.文本 not in ('+', '-'):
                break
            自己.位置 += 1
            右值 = 自己.分析乘除()
            if 右值 is None:
                自己.报错('运算缺少右边的值')
            左值 = 语法树(节点运算, [词元对象, 左值, 右值])
        return 左值

    def 分析匿名函数(自己):
        """匿名函数：(参数) { ... }，只用于参数位置。

        先找到配对的右括号，再看它后面是否紧跟 {{，
        只有紧跟 {{ 才认定是匿名函数，否则退回普通括号。
        调用时把参数逐个绑定，返回值就是函数体的返回值。
        """
        起始 = 自己.位置
        if not 自己.读符号('('):
            return None

        # 先跳过参数部分，找到配对的右括号
        深度 = 1
        扫描位置 = 自己.位置
        while 扫描位置 < 自己.数量:
            文本 = 自己.词元列表[扫描位置].文本
            if 文本 == '(':
                深度 += 1
            elif 文本 == ')':
                深度 -= 1
                if 深度 == 0:
                    break
            扫描位置 += 1

        if 深度 != 0:
            自己.位置 = 起始
            return None

        # 右括号后面必须是 { 才算匿名函数
        下一个 = 扫描位置 + 1
        if 下一个 >= 自己.数量 or 自己.词元列表[下一个].文本 != '{':
            自己.位置 = 起始
            return None

        参数节点 = 自己.分析参数定义()
        if 参数节点 is None or not 自己.读符号(')'):
            自己.位置 = 起始
            return None
        语句节点 = 自己.分析语句块()
        if 语句节点 is None:
            自己.位置 = 起始
            return None
        return 语法树(节点匿名函数, [参数节点, 语句节点])

    def 分析参数项(自己):
        """参数项：值、调用结构或调用名称。

        「真」「假」在这里是状态字面量，其余名称是调用名称。
        """
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None

        # 匿名函数：直接写成 (参数) { ... }，只能出现在参数位置
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '(':
            匿名 = 自己.分析匿名函数()
            if 匿名 is not None:
                return 匿名

        # 参数里也可能出现算术运算，如 -3、1 + 2
        起始 = 自己.位置
        表达式 = 自己.分析单项表达式()
        if 表达式 is not None:
            下个 = 自己.当前()
            是运算 = isinstance(表达式, 语法树) \
                and 表达式.data in (节点运算, 节点比较)
            是字面量 = isinstance(表达式, 语法树) and 表达式.data in (
                节点值, 节点名称)
            if 是运算 or 是字面量 or 下个 is None or 下个.文本 in (',', ')'):
                return 表达式
            自己.位置 = 起始

        if 词元对象.种类 == 名称类 and 词元对象.文本 not in 状态字面量:
            # 调用：name(...) 或 模块.name(...)
            if 自己.是否文本('(', 1) or 自己.是否文本('.', 1):
                return 自己.分析调用结构()
            return 自己.分析调用名称()
        return 自己.分析值()

    def 分析调用名称(自己):
        """单独的名称用法。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 语法树(节点调用名称, [名称节点])

    def 分析数据(自己):
        """数据：值、调用结构、调用名称，或管道调用。返回 data 节点。"""
        起始 = 自己.位置
        管道节点 = 自己.分析管道调用()
        if 管道节点 is not None:
            return 语法树(节点数据, [管道节点])
        自己.位置 = 起始
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None

        # 数据里可能出现算术或比较，如 "." + 名、甲 <= 乙、切片 + 文本
        表达式 = 自己.分析表达式()
        if 表达式 is not None:
            下个 = 自己.当前()
            是复合 = isinstance(表达式, 语法树) and 表达式.data in (
                节点运算, 节点比较, 节点成员运算, 节点切片, 节点值)
            # 后面紧跟运算符，说明这段表达式还要继续参与运算
            后续是运算 = 下个 is not None and 下个.种类 == 符号类 \
                and 下个.文本 in ('+', '-', '*', '/', '%', '==', '!=', '<',
                                  '>', '<=', '>=')
            if 是复合 or 后续是运算 or 下个 is None:
                return 语法树(节点数据, [表达式])
            自己.位置 = 起始

        # 调用：name(...) 或 模块.name(...)
        if 词元对象.种类 == 名称类 and (
                自己.是否文本('(', 1) or 自己.是否文本('.', 1)):
            调用节点 = 自己.分析调用结构()
            if 调用节点 is None:
                return None
            return 语法树(节点数据, [调用节点])
        if 词元对象.种类 == 名称类 and 词元对象.文本 not in 状态字面量:
            名称节点 = 自己.分析调用名称()
            if 名称节点 is None:
                return None
            # 名称后面可能跟下标或切片，如 a[1:3]
            名称节点 = 自己.分析下标(名称节点)
            if 名称节点 is None:
                return None
            return 语法树(节点数据, [名称节点])
        值节点 = 自己.分析值()
        if 值节点 is None:
            return None
        return 语法树(节点数据, [值节点])

    def 分析值(自己):
        """值：数字、文本、状态、列表、对象。返回 value 节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 数字符号:
            自己.位置 += 1
            return 语法树(节点值, [语法树(节点数值, [词元对象])])
        if 词元对象.种类 == 文本符号:
            自己.位置 += 1
            return 语法树(节点值, [语法树(节点文本, [词元对象])])
        if 词元对象.种类 == 名称类 and 词元对象.文本 in 状态字面量:
            自己.位置 += 1
            return 语法树(节点值, [语法树(节点状态, [])])
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '[':
            列表节点 = 自己.分析列表()
            return None if 列表节点 is None else 语法树(节点值, [列表节点])
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '{':
            对象节点 = 自己.分析对象()
            return None if 对象节点 is None else 语法树(节点值, [对象节点])
        # 变量名也可以作为值，如 {名字: 名字}
        if 词元对象.种类 == 名称类:
            名称节点 = 自己.分析名称()
            return None if 名称节点 is None else 语法树(节点值, [名称节点])
        return None

    def 分析列表(自己):
        """[值, 值, ...]，允许为空。"""
        if not 自己.读符号('['):
            return None
        值列表 = []
        if not 自己.是否文本(']'):
            while True:
                值节点 = 自己.分析列表项()
                if 值节点 is None:
                    return None
                值列表.append(值节点)
                if not 自己.读符号(','):
                    break
        if not 自己.读符号(']'):
            return None
        return 语法树(节点列表, 值列表)

    def 分析列表项(自己):
        """列表项：值、名称或表达式。"""
        表达式 = 自己.分析表达式()
        if 表达式 is not None:
            return 表达式
        return 自己.分析值()

    def 分析对象(自己):
        """{键: 值, ...}，允许为空。"""
        if not 自己.读符号('{'):
            return None
        键值对列表 = []
        if not 自己.是否文本('}'):
            while True:
                键节点 = 自己.分析键()
                if 键节点 is None or not 自己.读符号(':'):
                    return None
                值节点 = 自己.分析值()
                if 值节点 is None:
                    return None
                键值对列表.append(语法树(节点键值对, [键节点, 值节点]))
                if not 自己.读符号(','):
                    break
        if not 自己.读符号('}'):
            return None
        return 语法树(节点对象, 键值对列表)

    def 分析键(自己):
        """键：名称、文本或整数。返回 key 节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 名称类:
            名称节点 = 自己.分析名称()
            return None if 名称节点 is None else 语法树(节点键, [名称节点])
        if 词元对象.种类 == 文本符号:
            自己.位置 += 1
            return 语法树(节点键, [语法树(节点文本, [词元对象])])
        if 词元对象.种类 == 数字符号:
            自己.位置 += 1
            return 语法树(节点键, [语法树(节点整数, [语法树(节点自然数, [词元对象])])])
        return None


def 语言词法分析(代码文本, 语法分析=False):
    """词法分析入口。

    只给代码文本时返回词元列表；语法分析=True 时返回词元列表与语法树。
    """
    词元列表 = 扫描词元(代码文本)
    if not 语法分析:
        return 词元列表
    if not 词元列表:
        raise 词法错误('代码为空', 1, 1, 0)
    语法树对象 = 分析器(词元列表).分析程序()
    return 词元列表, 语法树对象
