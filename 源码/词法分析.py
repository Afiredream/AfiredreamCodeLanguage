"""词法分析

使用原生 Python 语法实现词法解析，完全替代原来的 lark 模块。

整体流程：

    代码文本 ──词法扫描──> 词元列表 ──未归约词分析──> 语法树

词法扫描只依据字符本身切分词元（数字、文本、名称、符号）。
关键字与状态字面量（真 / 假）的含义由「未归约词分析」按上下文确定：
同一个词在语句开头是关键字，在表达式里是名称，在值的位置上才是状态。

未归约词分析采用「递归下降」：每种语句、每种值各有一段分析函数，
读不通就退回原位再试其它写法。

对外接口：

    语言词法分析(代码文本)                 仅词法扫描，返回词元列表
    语言词法分析(代码文本, 语法分析=True)   词法扫描 + 未归约词分析，返回语法树
"""

