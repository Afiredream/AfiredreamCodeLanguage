# ── 词元 ──────────────────────────────────────────────────────────

class 词元(str):
    """一个词元。

    与 lark 的 Token 一样继承自 str：词元本身就是它的原文，可以直接参与
    字符串运算，也可以 int(词元) 转成数字。另外附带位置与语法含义信息。
    """

    __slots__ = ('种类', '行号', '列号', '起始位置', '结束位置',
                 '词元类型', '限制')

    def __new__(类, 种类, 文本, 行号, 列号, 起始位置, 结束位置,
                词元类型='', 限制=None):
        对象 = super().__new__(类, 文本)
        对象.种类 = 种类
        对象.行号 = 行号
        对象.列号 = 列号
        对象.起始位置 = 起始位置
        对象.结束位置 = 结束位置
        对象.词元类型 = 词元类型
        对象.限制 = 限制
        return 对象

    @property
    def 文本(自己):
        return str(自己)

    def 改名(自己, 词元类型, 限制=None):
        """返回含义被重新认定的同一个词元。"""
        return 词元(自己.种类, str(自己), 自己.行号, 自己.列号,
                    自己.起始位置, 自己.结束位置, 词元类型, 限制)

    def __repr__(自己):
        return f"词元({自己.词元类型!r}, {str(自己)!r})"


# ── 语法树 ────────────────────────────────────────────────────────

class 语法树:
    """与 lark 的 Tree 结构一致，保证下游代码无需修改。"""

    __slots__ = ('data', 'children')

    def __init__(自己, data, children):
        自己.data = data
        自己.children = children

    def __eq__(自己, 其他):
        return (isinstance(其他, 语法树)
                and 自己.data == 其他.data
                and 自己.children == 其他.children)

    def __hash__(自己):
        return hash((自己.data, tuple(自己.children)))

    def __repr__(自己):
        return f"语法树({自己.data!r}, {自己.children!r})"

    def __len__(自己):
        return len(自己.children)

    def 迭代词元(自己):
        """按出现顺序产出所有词元。"""
        for 子节点 in 自己.children:
            if isinstance(子节点, 词元):
                yield 子节点
            elif isinstance(子节点, 语法树):
                yield from 子节点.迭代词元()

    def scan_values(自己, 条件):
        """等价于 lark 的 scan_values。"""
        for 词元对象 in 自己.迭代词元():
            if 条件(词元对象):
                yield 词元对象

    def pretty(自己, 缩进='  '):
        """等价于 lark 的 pretty()。"""
        行列表 = []
        自己._美化(行列表, 0, 缩进)
        return '\n'.join(行列表)

    def _美化(自己, 行列表, 层数, 缩进):
        if 自己.data:
            行列表.append(缩进 * 层数 + str(自己.data))
            层数 += 1
        for 子节点 in 自己.children:
            if isinstance(子节点, 语法树):
                子节点._美化(行列表, 层数, 缩进)
            else:
                行列表.append(缩进 * 层数 + str(子节点))


# ── 错误 ──────────────────────────────────────────────────────────

class 词法错误(Exception):
    """词法分析或语法分析过程中发现的错误。"""

    def __init__(自己, 说明, 行号, 列号, 位置):
        super().__init__(f'{说明}（第 {行号} 行第 {列号} 列）')
        自己.说明 = 说明
        自己.行号 = 行号
        自己.列号 = 列号
        自己.位置 = 位置


# ── 字符判断 ──────────────────────────────────────────────────────

def 是空白(字符):
    return bool(字符) and 字符.isspace()


def 是数字(字符):
    return bool(字符) and '0' <= 字符 <= '9'


def 是汉字(字符):
    if not 字符:
        return False
    编码 = ord(字符)
    return (0x4E00 <= 编码 <= 0x9FFF        # 基本汉字
            or 0x3400 <= 编码 <= 0x4DBF     # 扩展 A 区
            or 0x20000 <= 编码 <= 0x2A6DF   # 扩展 B 区
            or 0x2A700 <= 编码 <= 0x2CEAF   # 扩展 C 至 G 区
            or 0xF900 <= 编码 <= 0xFAFF     # 兼容汉字
            or 0x2F800 <= 编码 <= 0x2FA1F)  # 兼容汉字补充


def 是名称字符(字符):
    return (bool(字符) and (字符 == '_' or 是汉字(字符)
                            or 'a' <= 字符 <= 'z' or 'A' <= 字符 <= 'Z'
                            or 是数字(字符)))


符号集合 = frozenset('(){}[],:=|.?')


# ── 词法扫描 ──────────────────────────────────────────────────────

def 记录行列(代码文本):
    """预先算好每个字符所在的行号与列号（均从 1 开始）。"""
    行号表 = [0] * (len(代码文本) + 1)
    列号表 = [0] * (len(代码文本) + 1)
    行号, 列号 = 1, 1
    for 序号, 字符 in enumerate(代码文本):
        行号表[序号] = 行号
        列号表[序号] = 列号
        行号, 列号 = (行号 + 1, 1) if 字符 == '\n' else (行号, 列号 + 1)
    行号表[len(代码文本)] = 行号
    列号表[len(代码文本)] = 列号
    return 行号表, 列号表


def 扫描词元(代码文本):
    """把代码文本切分为词元列表（忽略空白）。"""
    行号表, 列号表 = 记录行列(代码文本)
    词元列表 = []
    长度 = len(代码文本)
    位置 = 0

    def 生成(种类, 类型, 起, 止):
        return 词元(种类, 代码文本[起:止], 行号表[起], 列号表[起],
                    起, 止, 类型)

    while 位置 < 长度:
        字符 = 代码文本[位置]

        if 是空白(字符):
            位置 += 1
            continue

        起始位置 = 位置

        if 是数字(字符):
            while 位置 < 长度 and 是数字(代码文本[位置]):
                位置 += 1
            if 位置 + 1 < 长度 and 代码文本[位置] == '.' \
                    and 是数字(代码文本[位置 + 1]):
                位置 += 1
                while 位置 < 长度 and 是数字(代码文本[位置]):
                    位置 += 1
            词元列表.append(生成(数字符号, 数字类型, 起始位置, 位置))

        elif 是名称字符(字符):
            while 位置 < 长度 and 是名称字符(代码文本[位置]):
                位置 += 1
            词元列表.append(生成(名称类, '', 起始位置, 位置))

        elif 字符 in ('"', "'"):
            引号 = 字符
            位置 += 1
            while 位置 < 长度 and 代码文本[位置] != 引号:
                位置 += 1
            if 位置 >= 长度:
                raise 词法错误('文本缺少结尾的引号', 行号表[起始位置],
                               列号表[起始位置], 起始位置)
            位置 += 1
            词元列表.append(生成(文本符号, 文本类型, 起始位置, 位置))

        elif 字符 in 符号集合:
            位置 += 1
            词元列表.append(生成(符号类, 字符, 起始位置, 位置))

        else:
            raise 词法错误(f'无法识别的字符「{字符}」', 行号表[起始位置],
                           列号表[起始位置], 起始位置)

    return 词元列表


# ══════════════════════════════════════════════════════════════════
# 未归约词分析
#
# 关键字与状态字面量没有在词法扫描阶段固定下来，而是由分析器按所处位置
# 现场判断：
#
#     语句开头    命中「语句关键字」的词开启对应语句，其余当作调用
#     名称位置    类型名、变量名、参数名、键：一律当作名称
#     值的位置    只有「真」「假」才当作状态字面量
#     数据位置    名称既可当作调用名称，也可当作调用结构
#
# 语句内部出现的「模型」「函数」「循环」「如果」「或者」不能当作名称，
# 以免嵌套语句的边界被误读。
# ══════════════════════════════════════════════════════════════════


class 分析器:
    """把词元列表分析成语法树。"""

    def __init__(自己, 词元列表, 结束位置=None):
        自己.词元列表 = 词元列表
        自己.数量 = len(词元列表)
        自己.位置 = 0
        自己.结束位置 = 结束位置 or (词元列表[-1].结束位置 if 词元列表 else 0)

    # ── 基本工具 ────────────────────────────────────────────────

    def 当前(自己, 偏移=0):
        位置 = 自己.位置 + 偏移
        return 自己.词元列表[位置] if 位置 < 自己.数量 else None

    def 是否文本(自己, 文本, 偏移=0):
        词元对象 = 自己.当前(偏移)
        return 词元对象 is not None and 词元对象.文本 == 文本

    def 读符号(自己, 符号):
        """读到指定符号则前进，否则原地不动。"""
        词元对象 = 自己.当前()
        if 词元对象 is not None and 词元对象.种类 == 符号类 \
                and 词元对象.文本 == 符号:
            自己.位置 += 1
            return True
        return False

    def 读关键字(自己, 文本):
        """读到一个关键字，返回它的词元；否则返回 None。"""
        词元对象 = 自己.当前()
        if 词元对象 is None or 词元对象.种类 != 名称类 \
                or 词元对象.文本 != 文本:
            return None
        自己.位置 += 1
        return 词元对象

    def 报错(自己, 说明):
        词元对象 = 自己.当前()
        if 词元对象 is None and 自己.数量:
            末尾 = 自己.词元列表[-1]
            raise 词法错误(说明 + '：代码意外结束',
                           末尾.行号, 末尾.列号 + len(末尾), 末尾.结束位置)
        if 词元对象 is None:
            raise 词法错误(说明 + '：代码意外结束', 1, 1, 0)
        raise 词法错误(f'{说明}：遇到「{词元对象.文本}」',
                       词元对象.行号, 词元对象.列号, 词元对象.起始位置)

    # ── 名称 ────────────────────────────────────────────────────

    def 分析名称(自己):
        """读一个名称，返回 name 节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None or 词元对象.种类 != 名称类:
            return None
        自己.位置 += 1
        return 语法树(节点名称, [词元对象.改名(名称类型)])

    def 分析类型名(自己):
        """读一个类型名，返回 type(name(...)) 节点。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 语法树(节点类型, [名称节点])

    # ── 程序与语句 ──────────────────────────────────────────────

    def 分析程序(自己):
        return 语法树(节点开始, [自己.分析语句组()])

    def 分析语句组(自己):
        """一条或多条语句。"""
        语句列表 = []
        while 自己.位置 < 自己.数量:
            语句 = 自己.分析语句()
            if 语句 is None:
                if not 语句列表:
                    自己.报错('无法解析这条语句')
                break
            语句列表.append(语法树(节点语句项, [语句]))
        if not 语句列表:
            自己.报错('这里需要至少一条语句')
        return 语法树(节点语句组, 语句列表)

    def 分析语句(自己):
        """分析一条语句，返回语句节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 名称类 and 词元对象.文本 in 语句关键字:
            文本 = 词元对象.文本
            自己.位置 += 1
            语句 = 自己.分析关键字语句(语句关键字[文本])
            if 语句 is None:
                自己.报错(f'「{文本}」语句的写法不正确')
            return 语句
        return 自己.分析调用结构()

    def 分析关键字语句(自己, 规则名):
        if 规则名 in ('定义类型', '定义常量', '定义变量', '定义容量'):
            return 自己.分析定义(规则名)
        if 规则名 in ('模型结构', '函数结构'):
            return 自己.分析结构(规则名)
        if 规则名 == '循环语句':
            return 自己.分析循环()
        if 规则名 == '条件语句':
            return 自己.分析条件()
        return 自己.分析模块(规则名)

    def 分析定义(自己, 规则名):
        """类型 / 常量 / 变量 / 容量：类型 : 名称 = 数据"""
        类型节点 = 自己.分析类型名()
        if 类型节点 is None or not 自己.读符号(':'):
            return None
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        数据节点 = 自己.分析定义尾()
        if 数据节点 is None:
            return None
        return 语法树(节点名表[规则名], [类型节点, 名称节点, 数据节点])

    def 分析定义尾(自己):
        """定义中名称之后的部分：= 数据"""
        if not 自己.读符号('='):
            return None
        数据节点 = 自己.分析数据()
        if 数据节点 is None:
            return None
        return 数据节点

    def 分析结构(自己, 规则名):
        """模型 / 函数：类型 : 名称(参数){语句}"""
        类型节点 = 自己.分析类型名()
        if 类型节点 is None or not 自己.读符号(':'):
            return None
        名称节点 = 自己.分析名称()
        if 名称节点 is None or not 自己.读符号('('):
            return None
        参数节点 = 自己.分析参数定义()
        if 参数节点 is None or not 自己.读符号(')'):
            return None
        语句节点 = 自己.分析语句块()
        if 语句节点 is None:
            return None
        return 语法树(节点名表[规则名], [类型节点, 名称节点, 参数节点, 语句节点])

    def 分析参数定义(自己):
        """参数：类型 : 名称，可用逗号分隔多个，允许为空。"""
        参数列表 = []
        if not 自己.是否文本(')'):
            while True:
                类型节点 = 自己.分析类型名()
                if 类型节点 is None or not 自己.读符号(':'):
                    return None
                名称节点 = 自己.分析名称()
                if 名称节点 is None:
                    return None
                参数列表.append(语法树(节点参数节, [类型节点, 名称节点]))
                if not 自己.读符号(','):
                    break
        return 语法树(节点参数组, 参数列表)

    def 分析语句块(自己):
        """{ 语句组 }，返回 statements 节点。"""
        if not 自己.读符号('{'):
            return None
        语句组 = 自己.分析语句组()
        if not 自己.读符号('}'):
            return None
        return 语句组

    def 分析循环(自己):
        """循环(名称){语句}"""
        if not 自己.读符号('('):
            return None
        名称节点 = 自己.分析名称()
        if 名称节点 is None or not 自己.读符号(')'):
            return None
        语句组 = 自己.分析语句块()
        if 语句组 is None:
            return None
        return 语法树(节点循环, [名称节点, 语句组])

    def 分析条件(自己):
        """如果(名称){语句} 或者(名称){语句}"""
        if not 自己.读符号('('):
            return None
        名称节点 = 自己.分析名称()
        if 名称节点 is None or not 自己.读符号(')'):
            return None
        如果语句 = 自己.分析语句块()
        if 如果语句 is None:
            return None
        if 自己.读关键字('或者') is None or not 自己.读符号('('):
            return None
        或者名称 = 自己.分析名称()
        if 或者名称 is None or not 自己.读符号(')'):
            return None
        或者语句 = 自己.分析语句块()
        if 或者语句 is None:
            return None
        return 语法树(节点条件, [名称节点, 如果语句, 或者名称, 或者语句])

    def 分析模块(自己, 规则名):
        """导入 / 导出 名称"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 语法树(节点名表[规则名], [名称节点])

    # ── 调用 ────────────────────────────────────────────────────

    def 分析调用结构(自己):
        """调用结构：名称(参数列表)"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None or not 自己.读符号('('):
            return None
        参数节点 = 自己.分析参数列表()
        if 参数节点 is None or not 自己.读符号(')'):
            return None
        return 语法树(节点调用结构, [名称节点, 参数节点])

    def 分析参数列表(自己):
        """参数列表：参数项(, 参数项)*，允许为空。返回 arguments 节点。"""
        参数列表 = []
        if not 自己.是否文本(')'):
            while True:
                参数节点 = 自己.分析参数项()
                if 参数节点 is None:
                    return None
                参数列表.append(语法树(节点参数项, [参数节点]))
                if not 自己.读符号(','):
                    break
        return 语法树(节点参数列表, 参数列表)

    # ── 数据与值 ────────────────────────────────────────────────

    def 分析参数项(自己):
        """参数项：值、调用结构或调用名称。

        「真」「假」在这里是状态字面量，其余名称是调用名称。
        """
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 名称类 and 词元对象.文本 not in 状态字面量:
            if 自己.是否文本('(', 1):
                return 自己.分析调用结构()
            return 自己.分析调用名称()
        return 自己.分析值()

    def 分析调用名称(自己):
        """单独的名称用法。"""
        名称节点 = 自己.分析名称()
        if 名称节点 is None:
            return None
        return 语法树(节点调用名称, [名称节点])

    def 分析数据(自己):
        """数据：值、调用结构或调用名称。返回 data 节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 名称类 and 自己.是否文本('(', 1):
            调用节点 = 自己.分析调用结构()
            if 调用节点 is None:
                return None
            return 语法树(节点数据, [调用节点])
        if 词元对象.种类 == 名称类 and 词元对象.文本 not in 状态字面量:
            名称节点 = 自己.分析调用名称()
            if 名称节点 is None:
                return None
            return 语法树(节点数据, [名称节点])
        值节点 = 自己.分析值()
        if 值节点 is None:
            return None
        return 语法树(节点数据, [值节点])

    def 分析值(自己):
        """值：数字、文本、状态、列表、对象。返回 value 节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 数字符号:
            自己.位置 += 1
            return 语法树(节点值, [语法树(节点数值, [词元对象])])
        if 词元对象.种类 == 文本符号:
            自己.位置 += 1
            return 语法树(节点值, [语法树(节点文本, [词元对象])])
        if 词元对象.种类 == 名称类 and 词元对象.文本 in 状态字面量:
            自己.位置 += 1
            return 语法树(节点值, [语法树(节点状态, [])])
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '[':
            列表节点 = 自己.分析列表()
            return None if 列表节点 is None else 语法树(节点值, [列表节点])
        if 词元对象.种类 == 符号类 and 词元对象.文本 == '{':
            对象节点 = 自己.分析对象()
            return None if 对象节点 is None else 语法树(节点值, [对象节点])
        return None

    def 分析列表(自己):
        """[值, 值, ...]，允许为空。"""
        if not 自己.读符号('['):
            return None
        值列表 = []
        if not 自己.是否文本(']'):
            while True:
                值节点 = 自己.分析值()
                if 值节点 is None:
                    return None
                值列表.append(值节点)
                if not 自己.读符号(','):
                    break
        if not 自己.读符号(']'):
            return None
        return 语法树(节点列表, 值列表)

    def 分析对象(自己):
        """{键: 值, ...}，允许为空。"""
        if not 自己.读符号('{'):
            return None
        键值对列表 = []
        if not 自己.是否文本('}'):
            while True:
                键节点 = 自己.分析键()
                if 键节点 is None or not 自己.读符号(':'):
                    return None
                值节点 = 自己.分析值()
                if 值节点 is None:
                    return None
                键值对列表.append(语法树(节点键值对, [键节点, 值节点]))
                if not 自己.读符号(','):
                    break
        if not 自己.读符号('}'):
            return None
        return 语法树(节点对象, 键值对列表)

    def 分析键(自己):
        """键：名称、文本或整数。返回 key 节点。"""
        词元对象 = 自己.当前()
        if 词元对象 is None:
            return None
        if 词元对象.种类 == 名称类:
            名称节点 = 自己.分析名称()
            return None if 名称节点 is None else 语法树(节点键, [名称节点])
        if 词元对象.种类 == 文本符号:
            自己.位置 += 1
            return 语法树(节点键, [语法树(节点文本, [词元对象])])
        if 词元对象.种类 == 数字符号:
            自己.位置 += 1
            return 语法树(节点键, [语法树(节点整数, [语法树(节点自然数, [词元对象])])])
        return None


def 语言词法分析(代码文本, 语法分析=False):
    """词法分析入口。

    只给代码文本时返回词元列表；语法分析=True 时返回词元列表与语法树。
    """
    词元列表 = 扫描词元(代码文本)
    if not 语法分析:
        return 词元列表
    if not 词元列表:
        raise 词法错误('代码为空', 1, 1, 0)
    语法树对象 = 分析器(词元列表).分析程序()
    return 词元列表, 语法树对象
